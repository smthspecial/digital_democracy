#!/bin/sh
set -eu
# Shared RLS policy roles cannot log in. Per-app logins can connect only to their database.
psql --username "$POSTGRES_USER" --dbname postgres --set=go_password="$API_GO_PASSWORD" --set=app_password="$API_TS_APP_PASSWORD" --set=worker_password="$API_TS_WORKER_PASSWORD" <<'SQL'
CREATE ROLE api_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE ROLE api_worker NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE ROLE api_go_worker LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS PASSWORD :'go_password' IN ROLE api_worker;
CREATE ROLE api_ts_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS PASSWORD :'app_password' IN ROLE api_app;
CREATE ROLE api_ts_worker LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS PASSWORD :'worker_password' IN ROLE api_worker;
CREATE DATABASE api_go;
CREATE DATABASE api_ts;
REVOKE CONNECT ON DATABASE api_go FROM PUBLIC;
REVOKE CONNECT ON DATABASE api_ts FROM PUBLIC;
GRANT CONNECT ON DATABASE api_go TO api_go_worker;
GRANT CONNECT ON DATABASE api_ts TO api_ts_app,api_ts_worker;
SQL
